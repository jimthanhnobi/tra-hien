namespace TeaPremium.Domain.Crm;

public static class InteractionRules
{
    public const int MaxTextLength = CustomerRules.MaxInteractionContentLength;

    public const string NoteKind = "note";
    public const string CampaignMessageKind = "campaign_message";

    public const string DueToday = "today";
    public const string DueOverdue = "overdue";
    public const string DueWeek = "week";

    public static readonly string[] ChannelValues =
    [
        "zalo_personal", "zalo_oa", "phone", "facebook", "in_person", "email", "web", "other"
    ];

    public static readonly string[] AllKindValues =
    [
        "inquiry", "consultation", "quote", "follow_up", "complaint", "note", "campaign_message"
    ];

    // GAP-P204-01 = A (OWNER_APPROVED 2026-11-26): campaign_message is system-generated by P5-03 (BR-MKT-03),
    // never accepted on manual POST/PATCH .../interactions.
    public static readonly string[] ManualKindValues =
    [
        "inquiry", "consultation", "quote", "follow_up", "complaint", "note"
    ];

    public static readonly string[] FollowUpDueValues =
    [
        DueToday, DueOverdue, DueWeek
    ];

    public static IReadOnlySet<string> Channels => CustomerRules.InteractionChannels;

    public static IReadOnlySet<string> AllKinds => CustomerRules.InteractionKinds;

    public static readonly IReadOnlySet<string> ManualKinds = new HashSet<string>(ManualKindValues, StringComparer.Ordinal);

    public static readonly IReadOnlySet<string> FollowUpDueModes = new HashSet<string>(FollowUpDueValues, StringComparer.Ordinal);

    // Matches PostgreSQL length(content) BETWEEN 1 AND 4000 using Unicode scalar values (Rune)
    // and rejects NUL bytes / unpaired UTF-16 surrogates.
    public static bool IsValidText(string? raw)
    {
        if (string.IsNullOrWhiteSpace(raw) || !CustomerRules.IsValidPostgresText(raw))
        {
            return false;
        }

        var trimmed = raw.Trim();
        if (trimmed.Length == 0 || trimmed.Length > MaxTextLength * 2)
        {
            return false;
        }

        var runeCount = 0;
        foreach (var _ in trimmed.EnumerateRunes())
        {
            runeCount++;
            if (runeCount > MaxTextLength)
            {
                return false;
            }
        }

        return runeCount is >= 1 and <= MaxTextLength;
    }

    // BR-CRM-06 & ASSUMPTION-P204-03 = A: strict occurred_at <= now with zero positive clock skew.
    public static bool IsOccurredAtValid(DateTime occurredAtUtc, DateTime nowUtc)
        => occurredAtUtc <= nowUtc;

    // BR-CRM-06: follow_up_at must be strictly greater than occurred_at when scheduled.
    public static bool IsFollowUpAfterOccurred(DateTime occurredAtUtc, DateTime? followUpAtUtc)
        => followUpAtUtc is null || followUpAtUtc.Value > occurredAtUtc;

    public static bool IsValidSchedule(
        DateTime occurredAtUtc,
        DateTime? followUpAtUtc,
        DateTime nowUtc,
        out string? errorField,
        out string? errorCode)
    {
        if (!IsOccurredAtValid(occurredAtUtc, nowUtc))
        {
            errorField = "occurredAt";
            errorCode = "occurred_at_in_future";
            return false;
        }

        if (!IsFollowUpAfterOccurred(occurredAtUtc, followUpAtUtc))
        {
            errorField = "followUpAt";
            errorCode = "follow_up_before_or_equal_occurred_at";
            return false;
        }

        errorField = null;
        errorCode = null;
        return true;
    }

    // BR-CRM-07: all interaction kinds except 'note' count toward customers.last_contacted_at.
    public static bool CountsTowardLastContacted(string kind)
        => !string.Equals(kind, NoteKind, StringComparison.Ordinal);

    public static DateTime? MaxLastContacted(DateTime? current, DateTime occurredAtUtc)
        => current is null || occurredAtUtc > current.Value ? occurredAtUtc : current.Value;
}
