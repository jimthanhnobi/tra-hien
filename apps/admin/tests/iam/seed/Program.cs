using System.Security.Cryptography;
using System.Security.Cryptography.X509Certificates;
using System.Text.Json;
using Microsoft.EntityFrameworkCore;
using Microsoft.Extensions.Configuration;
using Microsoft.Extensions.DependencyInjection;
using Microsoft.Extensions.Logging;
using TeaPremium.Application.Iam;
using TeaPremium.Application.UseCases;
using TeaPremium.Infrastructure.Persistence;
using TeaPremium.Infrastructure.Iam;

var root = Path.GetFullPath("artifacts/p0-12-local");
var connection = File.ReadAllText(Path.Combine(root, "connection.secret"));
var parsed = new Npgsql.NpgsqlConnectionStringBuilder(connection);
if (parsed.Host != "127.0.0.1" || parsed.Database != "admin_shell_test")
    throw new InvalidOperationException("Seed only accepts the isolated loopback admin_shell_test database");
var configuration = new ConfigurationBuilder().AddInMemoryCollection(new Dictionary<string, string?> { ["ConnectionStrings:Default"] = connection }).Build();
var services = new ServiceCollection();
services.AddLogging(builder => builder.ClearProviders());
services.AddUseCasesFrom(typeof(StaffHandlers).Assembly);
services.AddPlatformPersistence(configuration);
services.AddStaffIdentity(configuration, false);
await using var provider = services.BuildServiceProvider();
await using var scope = provider.CreateAsyncScope();
await scope.ServiceProvider.GetRequiredService<AppDbContext>().Database.MigrateAsync();
var password = "T!" + Guid.NewGuid().ToString("N") + "aA1";
var newPassword = "T!" + Guid.NewGuid().ToString("N") + "bB2";
var email = "browser-owner@example.invalid";
var result = await scope.ServiceProvider.GetRequiredService<ICommandHandler<BootstrapOwner, bool>>().Handle(new(email, password), CancellationToken.None);
if (!result.IsSuccess || !result.Value) throw new InvalidOperationException("Test bootstrap failed");
var keyPassword = Guid.NewGuid().ToString("N");
using var rsa = RSA.Create(2048);
var request = new CertificateRequest("CN=P0-12 isolated test Data Protection", rsa, HashAlgorithmName.SHA256, RSASignaturePadding.Pkcs1);
using var certificate = request.CreateSelfSigned(DateTimeOffset.UtcNow.AddMinutes(-1), DateTimeOffset.UtcNow.AddDays(1));
var keyPath = Path.Combine(root, "data-protection.pfx");
File.WriteAllBytes(keyPath, certificate.Export(X509ContentType.Pfx, keyPassword));
File.WriteAllText(Path.Combine(root, "fixture.secret"), JsonSerializer.Serialize(new { email, password, newPassword, keyPath, keyPassword, connection }));
Console.WriteLine("Isolated test database migrated and fresh owner bootstrapped. Credentials not logged.");
